package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	var files []string
	filepath.WalkDir(".", func(p string, d os.DirEntry, e error) error {
		if e != nil {
			panic(e)
		}
		if d.IsDir() {
			if strings.HasPrefix(d.Name(), ".") && p != "." || p == "dist" || p == "bin" || p == "runtime" || p == "data" {
				return filepath.SkipDir
			}
			return nil
		}
		if p != "SOURCE_MAP.md" && p != "config.json" {
			files = append(files, filepath.ToSlash(p))
		}
		return nil
	})
	sort.Strings(files)
	b := []byte("<!-- Generated by tools/source-map.go; edit docs/architecture.md for responsibilities and flows. -->\n# Source map\n\nSee [architecture](docs/architecture.md) for entrypoints, routes, tests and data flows.\n\n")
	for _, p := range files {
		b = append(b, []byte("- `"+p+"`\n")...)
	}
	if len(os.Args) > 1 && os.Args[1] == "-check" {
		old, _ := os.ReadFile("SOURCE_MAP.md")
		if string(old) != string(b) {
			fmt.Fprintln(os.Stderr, "SOURCE_MAP.md is stale")
			os.Exit(1)
		}
	} else {
		if e := os.WriteFile("SOURCE_MAP.md", b, 0644); e != nil {
			panic(e)
		}
	}
}
